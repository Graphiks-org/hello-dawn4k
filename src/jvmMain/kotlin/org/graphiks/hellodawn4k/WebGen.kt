package org.graphiks.hellodawn4k

import java.io.File

/**
 * Emits the web app's generated assets from the single Kotlin source of truth:
 * the Cornell scene floats and the WGSL pass shaders (raw strings, safe inside
 * JS template literals). Run through the webGen task into webApp/generated/.
 */
fun main(args: Array<String>) {
    val dir = File(args.getOrElse(0) { "webApp/generated" }).apply { mkdirs() }
    val scene = CornellBox.scene()

    dir.resolve("scene.js").writeText(buildString {
        append("// GENERATED by WebGen — do not edit; regenerate with ./gradlew webGen\n")
        append("const QUADS = new Float32Array([\n")
        append(scene.quadData.joinToString(",\n") { value -> "${value}" })
        append(",\n]);\n")
        append("const QUAD_COUNT = ${scene.quadCount};\n")
        append("const LIGHT_INDEX = ${scene.lightIndex};\n")
    })

    fun shader(name: String, source: String) = "const $name = `$source`;\n"
    dir.resolve("shaders.js").writeText(buildString {
        append("// GENERATED by WebGen — do not edit; regenerate with ./gradlew webGen\n")
        append(shader("COMMON_WGSL", Shaders.COMMON_WGSL))
        append("\n")
        append(shader("RADIOSITY_WGSL", Shaders.RADIOSITY_WGSL))
        append("\n")
        append(shader("RAYTRACER_WGSL", Shaders.RAYTRACER_WGSL))
        append("\n")
        append(shader("RASTERIZER_WGSL", Shaders.RASTERIZER_WGSL))
        append("\n")
        append(shader("PRESENT_WGSL", Shaders.PRESENT_WGSL))
    })
    println("web assets written to ${dir.absolutePath}")
}
